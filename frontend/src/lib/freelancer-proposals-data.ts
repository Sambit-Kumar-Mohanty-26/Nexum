export function calculateProposalSummaryKPIs(
  proposals: FreelancerProposalItem[]
): ProposalSummaryKPIs {
  let underReview = 0;
  let shortlisted = 0;
  let interview = 0;
  let accepted = 0;
  let rejected = 0;
  let counteroffer = 0;
  let draft = 0;

  for (const p of proposals) {
    if (p.status === "UNDER_REVIEW" || p.status === "SUBMITTED") underReview++;
    else if (p.status === "SHORTLISTED") shortlisted++;
    else if (p.status === "INTERVIEW") interview++;
    else if (p.status === "ACCEPTED") accepted++;
    else if (p.status === "REJECTED") rejected++;
    else if (p.status === "COUNTEROFFER_RECEIVED") counteroffer++;
    else if (p.status === "DRAFT") draft++;
  }

  return {
    totalProposals: proposals.length,
    underReview,
    shortlisted,
    interview,
    accepted,
    rejected,
    counteroffer,
    draft,
  };
}

export function getProposalStatusBadgeConfig(status: ProposalStatus): {
  label: string;
  badgeClass: string;
} {
  switch (status) {
    case "ACCEPTED":
      return {
        label: "Accepted",
        badgeClass: "bg-emerald-50 text-emerald-700 border-emerald-200/80",
      };
    case "SHORTLISTED":
      return {
        label: "Shortlisted",
        badgeClass: "bg-emerald-50 text-emerald-700 border-emerald-200/80",
      };
    case "INTERVIEW":
      return {
        label: "Interview",
        badgeClass: "bg-indigo-50 text-indigo-700 border-indigo-200/80",
      };
    case "UNDER_REVIEW":
      return {
        label: "Under Review",
        badgeClass: "bg-amber-50 text-amber-700 border-amber-200/80",
      };
    case "COUNTEROFFER_RECEIVED":
      return {
        label: "Counteroffer Received",
        badgeClass: "bg-orange-50 text-orange-700 border-orange-200/80",
      };
    case "REJECTED":
      return {
        label: "Rejected",
        badgeClass: "bg-rose-50 text-rose-700 border-rose-200/80",
      };
    case "WITHDRAWN":
      return {
        label: "Withdrawn",
        badgeClass: "bg-slate-100 text-slate-600 border-slate-200",
      };
    case "DRAFT":
      return {
        label: "Draft",
        badgeClass: "bg-slate-100 text-slate-700 border-slate-200",
      };
    case "SUBMITTED":
    default:
      return {
        label: "Submitted",
        badgeClass: "bg-blue-50 text-blue-700 border-blue-200/80",
      };
  }
}
